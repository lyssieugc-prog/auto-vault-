"""Generate studio/place_markers.luau from the Blender layout.json (Blender Z-up -> Roblox Y-up).

    python3 games/ragdoll-off-a-mountain/studio/gen_markers.py

Blender (x, y, z) with Y north / Z up maps to Roblox (x, z, -y): Roblox is Y-up and its forward is -Z.
Each marker becomes an anchored, invisible, non-colliding Part under Workspace.Map.Markers whose
LookVector is the marker's facing (rotationY in degrees, 0 = facing +Y north in Blender).
"""

import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LAYOUT = os.path.join(HERE, "..", "assets", "export", "map", "layout.json")
OUT = os.path.join(HERE, "place_markers.luau")


def to_roblox(p):
    x, y, z = p
    return x, z, -y


def main(layout_path=LAYOUT, out_path=OUT):
    with open(layout_path) as f:
        layout = json.load(f)
    markers = layout["markers"] if isinstance(layout, dict) and "markers" in layout else layout
    if isinstance(markers, dict):
        markers = [dict(name=k, **v) for k, v in markers.items()]
    lines = [
        "-- GENERATED by studio/gen_markers.py from assets/export/map/layout.json. Do not edit by hand.",
        "-- Run in Studio (command bar or Studio MCP run_code) after importing the map chunks.",
        'local map = workspace:FindFirstChild("Map") or Instance.new("Model")',
        'map.Name = "Map"',
        "map.Parent = workspace",
        'local folder = map:FindFirstChild("Markers") or Instance.new("Folder")',
        'folder.Name = "Markers"',
        "folder.Parent = map",
        "local function marker(name, x, y, z, yaw, sx, sy, sz)",
        "\tlocal part = folder:FindFirstChild(name) or Instance.new(\"Part\")",
        "\tpart.Name = name",
        "\tpart.Anchored = true",
        "\tpart.CanCollide = false",
        "\tpart.CanQuery = false",
        "\tpart.Transparency = 1",
        "\tpart.Size = Vector3.new(sx, sy, sz)",
        "\tpart.CFrame = CFrame.new(x, y, z) * CFrame.Angles(0, math.rad(yaw), 0)",
        "\tpart.Parent = folder",
        "end",
    ]
    for m in markers:
        x, y, z = to_roblox(m["position"])
        yaw = float(m.get("rotationY", 0.0))
        size = m.get("size") or [4, 4, 1]
        if len(size) == 2:
            size = [size[0], size[1], 1]
        # Blender size (x, y, z) -> Roblox (x, z, y)
        sx, sy, sz = size[0], size[2], size[1]
        if m["name"] != "LandingZone" and sy < 1:
            sy = 1
        lines.append(
            f'marker("{m["name"]}", {x:.2f}, {y:.2f}, {z:.2f}, {yaw:.1f}, {sx:.2f}, {sy:.2f}, {sz:.2f})'
        )
    lines.append(f'print("[Markers] placed {len(markers)} markers")')
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out_path} ({len(markers)} markers)")


if __name__ == "__main__":
    main(*sys.argv[1:])
